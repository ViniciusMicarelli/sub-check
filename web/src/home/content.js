/** Formata em reais no padrão do idioma. */
export function money(value, lang, digits = 2) {
  const n = value.toLocaleString(lang === 'pt' ? 'pt-BR' : 'en-US', {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  })
  return `R$ ${n}`
}

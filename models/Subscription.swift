    func categorize(_ name: String) -> String {
        return normalizeBrand(name).mappedCategory
    }
    
    private func normalizeBrand(_ name: String) -> NormalizedBrand {
        let normalized = name.lowercased().replacingOccurrences(of: " ", with: "")
            .replacingOccurrences(of: "-", with: "")
            .replacingOccurrences(of: "_", with: "")
        
        if let match = brandMapping.firstKey(where: { normalized.contains($0) }) {
            return NormalizedBrand(name: name, match: match)
        }
        
        return NormalizedBrand(name: name, match: nil)
    }
    
    struct NormalizedBrand {
        let name: String
        let match: String?
        
        var mappedCategory: String {
            if let match = match {
                return brandMapping[match] ?? "Outros"
            }
            return "Outros"
        }
    }
